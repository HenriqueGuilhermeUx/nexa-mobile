const fs = require('fs');
const assert = require('assert');
const vm = require('vm');
const ts = require('typescript');
const source = fs.readFileSync('src/maya-actions/shoppingSearch.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }}).outputText;
const cjs = {};
vm.runInNewContext(js, { exports: cjs, Error, Number, encodeURIComponent });
const url = cjs.buildPublicShoppingSearchUrl('  celular  256 GB  ', 2500);
const parsed = new URL(url);
assert.strictEqual(parsed.origin, 'https://www.google.com');
assert.strictEqual(parsed.pathname, '/search');
assert.strictEqual(parsed.searchParams.get('tbm'), 'shop');
assert.strictEqual(parsed.searchParams.get('q'), 'celular 256 GB até R$ 2500');
assert.throws(() => cjs.buildPublicShoppingSearchUrl('x'));
assert.throws(() => cjs.buildPublicShoppingSearchUrl('celular bom', -1));
assert.throws(() => cjs.buildPublicShoppingSearchUrl('celular bom', 0.5));
assert.throws(() => cjs.buildPublicShoppingSearchUrl('celular bom', 1000001));
const screen = fs.readFileSync('app/maya-shopping.tsx', 'utf8');
const actions = fs.readFileSync('app/maya-actions.tsx', 'utf8');
const layout = fs.readFileSync('app/_layout.tsx', 'utf8');
assert(screen.includes('loadNexaSession()') && screen.includes('nexaApi.me(session.accessToken)'), 'Authenticated route required');
assert(screen.includes('WebBrowser.openBrowserAsync(url)') && screen.includes('onPress={() => { void openSearch(); }}'), 'Only user-initiated external search');
assert(screen.includes('não verifica nem compra produtos'), 'Must not claim automatic price verification');
assert(!/(sendPix|sendTransaction|executePayment|processPayment|createOrder)/.test(screen), 'No transaction');
assert(actions.includes("router.push('/maya-shopping'"), 'Actions entry missing');
assert(layout.includes('name="maya-shopping"'), 'Search route missing');
console.log('PASS wave 09: user-confirmed public shopping search; no automatic purchase or comparison claims');
