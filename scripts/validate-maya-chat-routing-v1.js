const fs = require('fs');
const assert = require('assert');
const vm = require('vm');
const ts = require('typescript');
const src = fs.readFileSync('src/maya-actions/chatIntent.ts','utf8');
const js = ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const lib = {};
vm.runInNewContext(js,{exports:lib});
const parse = lib.parseMayaLocalActionIntent;
assert.strictEqual(parse('Maya, pesquise preços de um notebook').kind,'shopping_search');
assert.strictEqual(parse('Maya, me lembre de pagar a internet').kind,'reminder_draft');
assert.strictEqual(parse('Compare ofertas de geladeira').kind,'shopping_search');
assert.strictEqual(parse('Traga R$ 2.000 do banco todo dia 8'),null);
assert.strictEqual(parse('Maya pesquise o preço do dólar'),null);
assert.strictEqual(parse('Maya me lembre de transferir 5 USDC'),null);
assert.strictEqual(parse('Quero comprar Bitcoin'),null);
assert.strictEqual(parse('O que é uma transferência PIX?'),null);
assert.strictEqual(parse('Como está meu dinheiro hoje?'),null);
assert.strictEqual(parse('Quais são minhas prioridades hoje?'),null);
const assistant = fs.readFileSync('src/components/NexaAssistantOpenFinance.tsx','utf8');
const shopping = fs.readFileSync('app/maya-shopping.tsx','utf8');
const tasks = fs.readFileSync('app/maya-actions.tsx','utf8');
assert(assistant.indexOf('parseRecurringFundingIntent(message)') < assistant.indexOf('parseMayaLocalActionIntent(message)'), 'Funding intents must keep precedence');
assert(assistant.indexOf("router.push('/open-finance')") < assistant.indexOf('parseMayaLocalActionIntent(message)'), 'Open Finance routing must keep precedence');
assert(assistant.indexOf('parseMayaLocalActionIntent(message)') < assistant.indexOf('nexaApi.assistantChat(token, message, history)'), 'Conservative local actions precede generic chat only');
assert(assistant.includes("pathname: '/maya-shopping'") && assistant.includes("pathname: '/maya-actions'"), 'Routes missing');
assert(shopping.includes('useLocalSearchParams') && shopping.includes('params.query'), 'Search prefill missing');
assert(tasks.includes('params.task') && tasks.includes("setKind('reminder')"), 'Reminders must be draft-only');
assert(!/(fetch\(|axios\.|executePayment|sendPix)/.test(src), 'Intent parsing must not execute remote or financial actions');
console.log('PASS Maya chat action routing: explicit shopping/reminder drafts; Open Finance and wallet intents preserved');
