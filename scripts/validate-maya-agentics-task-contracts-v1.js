const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const ts=require('typescript');
const src=fs.readFileSync('src/maya-actions/agenticsTaskContracts.ts','utf8');
assert.doesNotMatch(src,/\bfetch\s*\(|axios\.|sendPix\(|sendTransaction\(|executePayment\(|WebBrowser\.openBrowserAsync/,'Contract may not execute any work');
const compiled=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const out={};
vm.runInNewContext(compiled,{exports:out,Set,URL,Date,Number,Array,RegExp});
const check=out.validateMayaAgenticTask;
const now=Date.parse('2026-11-15T23:10:00.000Z');
const base={id:'abc-task_0001',ownerUserId:'user01',origin:'nexa_agentics',intent:'research',mode:'read_only',status:'completed',title:'Pesquisa autorizada',createdAt:'2026-11-15T23:00:00.000Z',updatedAt:'2026-11-15T23:08:00.000Z'};
assert.ok(check(base,'user01',now));
assert.equal(check(base,'user02',now),null,'cross account rejected');
assert.equal(check({...base,intent:'send_pix'},'user01',now),null,'money effect rejected');
assert.equal(check({...base,origin:'third_party'},'user01',now),null,'untrusted origin rejected');
assert.equal(check({...base,evidence:[{title:'Offer',url:'http://merchant.com',observedAt:base.createdAt}]},'user01',now),null,'unsafe evidence rejected');
const approved={...base,mode:'approved_nonfinancial',intent:'form_draft',status:'running'};
assert.equal(check(approved,'user01',now),null,'missing approval rejected');
assert.ok(check({...approved,approval:{approvedByUserId:'user01',approvedAt:base.createdAt,expiresAt:'2026-11-16T00:00:00.000Z',scope:'Prepare a draft only'}},'user01',now));
assert.equal(check({...approved,approval:{approvedByUserId:'user01',approvedAt:base.createdAt,expiresAt:'2026-11-15T23:09:00.000Z',scope:'Prepare a draft only'}},'user01',now),null,'expired approval rejected');
console.log('PASS Maya Agentics Phase3B client contracts: identity, expiry, scope, evidence, nonfinancial boundaries, no effects');
