const fs=require('node:fs'),ts=require('typescript'),vm=require('node:vm'),assert=require('node:assert/strict');
const src=fs.readFileSync('src/maya-actions/agenticsReadiness.ts','utf8');
assert.doesNotMatch(src,/\bfetch\s*\(|axios\.|Authorization:|Bearer |AGENTICS_API_KEY|EXPO_PUBLIC_.*SECRET/);
const out={};
vm.runInNewContext(ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:out,Set,Array,Object});
const parse=out.parseMayaAgenticsReadiness,off=out.MAYA_AGENTICS_DISABLED;
const raw={contract:'nexa-maya-agentics-bridge-v1',available:true,mode:'review_only',authenticatedByNexa:true,actorUserId:'nexa-user-123',userScopedJobs:true,externalEffects:false,financialExecution:false,supportedIntents:['research','calendar_draft']};
