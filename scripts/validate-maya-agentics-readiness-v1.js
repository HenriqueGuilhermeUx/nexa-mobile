assert.equal(parse({...raw,userScopedJobs:false},user).available,false);
assert.equal(parse({...raw,authenticatedByNexa:false},user).available,false);
assert.equal(parse({...raw,externalEffects:true},user).available,false);
assert.equal(parse({...raw,financialExecution:true},user).available,false);
assert.equal(parse({...raw,supportedIntents:['send_pix']},user).available,false);
assert.equal(parse({...raw,mode:'isolated_core'},user).available,false);
assert.equal(parse({mode:'isolated_core',financialExecution:false,customerDataAccess:false},user).available,false);
assert.equal(parse(null,user).available,false);
assert.equal(parse(raw,'').available,false);
assert.deepEqual(Array.from(parse(raw,user).supportedIntents),['research','calendar_draft']);
